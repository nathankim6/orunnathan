/**
 * SOURCED 층 — 출처가 붙은 자료.
 *
 * FACT(공시)·OBS(우리가 본 것)·VIEW(우리 생각)와 별개로,
 * "어디에 언제 무엇이 공개됐는가"를 그대로 옮긴 층이다.
 * 모든 항목에 source(url·제목·날짜)가 붙고, 문장은 원문의 뜻을 바꾸지 않는다.
 *
 * 옳은영어가 직접 본 것만 담는다. 시험지, 설명회, 재원생 이야기.
 * 학원 자체 집계는 basis에 분모를 적어 둔다.
 */

export interface Source {
  url: string;
  title: string;
  /** YYYY-MM-DD */
  date: string;
}

export type ExamTerm = "2026-1 중간" | "2026-1 기말";

export interface ExamReport {
  term: ExamTerm;
  grade: 1 | 2 | 3;
  /** 문항 구성 — 예: "객관식 28 · 서답형 0" */
  format: string;
  /** 시험 범위 */
  scope?: string;
  /** 난이도 한 줄 */
  difficulty: string;
  /** 등급을 가른 문항·유형 */
  killers: string[];
  cut?: { grade1?: string; grade2?: string; avg?: string };
  /** 담당 강사 총평 한 줄 */
  verdict: string;
  teacher?: string;
  source: Source;
}

export interface ResultClaim {
  label: string;
  /** 표시값 — "35%", "9명", "전교 1등" */
  value: string;
  /** 분모·기준 */
  basis: string;
  term: string;
  source: Source;
}

export interface Insight {
  text: string;
  source: Source;
}

export interface SourcedSchool {
  code: string;
  /** 2026년 1학기 시험 분석 */
  exams: ExamReport[];
  /** 옳은영어가 공개한 실적 */
  results: ResultClaim[];
  /** 선배들이 후배에게 — 학교 생활 TMI */
  tmi: string[];
  /** 설명회에서 강사가 말한 것 */
  insights: Insight[];
  /** 학교를 한 줄로 (출처 있는 말만 조합) */
  oneLiner?: string;
}



export const getBlankMultiplePrompt = (text: string, paraphrase: boolean = true) => {
  // Check if text contains user-specified blanks
  const hasUserBlanks = text.includes('[') && text.includes(']');
  
  // Store the original bracketed text for later use in explanation
  const originalExpressions: string[] = [];
  if (hasUserBlanks) {
    const matches = text.match(/\[(.*?)\]/g);
    if (matches) {
      matches.forEach(match => {
        originalExpressions.push(match.slice(1, -1)); // Remove the brackets
      });
    }
  }
  
  const promptText = hasUserBlanks 
    ? text.replace(/\[(.*?)\]/g, '_'.repeat(10)) // Replace bracketed text with underscores
    : text;

  const correctAnswerRule = paraphrase
    ? `### **STEP 3: 정답 선택지 작성 (패러프레이즈 - 변형 모드)**
- 원문 빈칸 표현의 모든 단어를 **금지 단어**로 설정
- 같은 의미를 **완전히 다른 단어/구문**으로 표현 (수동/능동, 명사구/동사구 변환 등)
- 원문 표현이 그대로 선택지에 나타나면 절대 안 됨
- 검증: 정답 선택지에 금지 단어가 하나라도 있으면 다시 작성`
    : `### **STEP 3: 정답 선택지 작성 (원본 그대로 - 원본 모드)**
- 원문 빈칸 표현을 **있는 그대로** 정답 선택지로 사용
- 패러프레이즈하지 말고 원문 표현 그대로 정답 선택지로 제시
- 오답 4개는 원문 표현과 명확히 다른 의미여야 함`;

  const noReuseRule = paraphrase
    ? `1. ❌ 원문의 빈칸 표현이 선택지에 나타나면 절대 안 됩니다
2. ❌ 원문의 빈칸 표현과 한 단어라도 겹치는 선택지는 절대 금지
3. ❌ 정답이 2개 이상 되는 문제를 절대 만들지 마세요
4. ✅ 정답 선택지는 원문과 완전히 다른 단어로 패러프레이즈되어야 합니다`
    : `1. ✅ 정답 선택지는 원문의 빈칸 표현과 **완전히 일치**해야 합니다
2. ❌ 정답이 2개 이상 되는 문제를 절대 만들지 마세요
3. ✅ 오답 4개는 원문 표현과 의미가 명확히 다른 표현이어야 합니다`;

  const explanationRule = paraphrase
    ? `[해설] 이 글은 [핵심 내용 요약]을 설명하고 있습니다. 정답 ○번은 원문의 의미를 적절히 패러프레이즈한 표현입니다.
원문의 빈칸 표현: ${hasUserBlanks ? `[${originalExpressions.join(', ')}]` : '[원문의 빈칸 표현]'}
패러프레이즈 설명: 원문의 "[원문 표현]"을(를) 같은 의미의 "[정답 선택지 표현]"(으)로 변형했습니다.`
    : `[해설] 이 글은 [핵심 내용 요약]을 설명하고 있습니다. 정답 ○번은 원문의 표현을 그대로 사용한 선택지입니다.
원문의 빈칸 표현: ${hasUserBlanks ? `[${originalExpressions.join(', ')}]` : '[원문의 빈칸 표현]'} (원본 그대로 정답으로 출제됨)`;

  return `당신은 수능 영어 빈칸 추론 문제 전문가입니다. 아래 제공된 **정확한 지문**을 사용하여 빈칸 추론 문제를 만드세요.

🚨🚨🚨 **최우선 절대 규칙: 원문 무결성 (Source Integrity)** 🚨🚨🚨
- **반드시 아래 [입력 지문] 섹션의 텍스트만 사용하세요.**
- ❌ **새로운 지문을 만들거나, 다른 지문으로 교체하거나, 임의로 패러프레이즈하지 마세요.**
- ❌ **문장을 추가/삭제/순서변경하지 마세요.** 빈칸 부분만 ______ 로 대체하고 나머지는 단어 하나도 바꾸지 마세요.
- ✅ 출력의 지문 부분은 [입력 지문]과 **글자 단위로 동일**해야 합니다 (빈칸 처리된 부분 제외).

---

## 📥 [입력 지문] (이 지문만 사용할 것)

${promptText}

---

🚨 **선택지 규칙 (현재 모드: ${paraphrase ? '변형 모드' : '원본 모드'})**
${noReuseRule}
5. ❌ 원문에 없는 새로운 문장을 추가하여 빈칸으로 만들지 마세요
6. ✅ 반드시 [입력 지문]에 이미 존재하는 구문/문장의 일부를 빈칸으로 처리해야 합니다

---

## 📋 Step-by-Step 문제 생성 프로세스

### **STEP 1: 원문 분석**
${hasUserBlanks 
  ? `- 사용자가 대괄호로 표시한 부분: "${originalExpressions.join(', ')}"
- 이 표현이 빈칸이 됩니다 (이미 [입력 지문]에서 ______ 로 처리됨)`
  : `- 🚨 **반드시 [입력 지문]에 이미 존재하는 문장/구문 중에서** 핵심 주제를 가장 잘 반영하는 부분을 선택하여 빈칸으로 만드세요
- ❌ **절대로 [입력 지문]에 없는 새로운 문장을 만들어 빈칸으로 사용하지 마세요**
- ✅ [입력 지문]의 특정 구문을 ______ 으로 대체하고, 나머지 지문은 **한 글자도 바꾸지 말고** 그대로 유지하세요`}

### **STEP 2: 정답 번호 먼저 결정 (랜덤)**
- 🎲 1~5 사이의 숫자를 무작위로 선택 (①②③④⑤ 각 20% 확률)
- ⚠️ ④번이나 ⑤번에만 편향되지 마세요

${correctAnswerRule}

### **STEP 4: 오답 선택지 4개 작성**
- 정답과 명확히 다른 의미
- 유형: 반대 의미 / 무관한 표현 / 문맥상 틀린 표현

### **STEP 5: 복수 정답 방지 검증**
- 정답 선택지만 원문 의미와 일치하는가?
- 정답이 정확히 1개인가?

### **STEP 6: 최종 출력**

다음 순서로 출력하세요 (코드블록 없이, 바로 출력):

다음 글의 빈칸에 들어갈 말로 가장 적절한 것은?

[여기에 위 [입력 지문]을 글자 단위로 동일하게 복사하되, 빈칸 부분만 ______ 로 표시]

① [선택지 1]
② [선택지 2]
③ [선택지 3]
④ [선택지 4]
⑤ [선택지 5]

[정답] ○번

${explanationRule}

---

## ⚠️ 최종 검증 (출력 전 필수)

**검증 1: 원문 무결성** 🚨🚨🚨
- [ ] 출력한 지문이 [입력 지문]과 **글자 단위로 동일**한가? (빈칸 부분 제외)
- [ ] 새로운 문장을 추가하거나 다른 지문으로 바꾸지 않았는가?

**검증 2: 정답 선택지 (현재 모드: ${paraphrase ? '변형' : '원본'})**
${paraphrase
  ? `- [ ] 정답이 정확히 1개이고, 원문 빈칸 단어를 사용하지 않았는가?
- [ ] 정답이 원문 표현과 같은 의미의 다른 단어/구문으로 패러프레이즈되었는가?`
  : `- [ ] 정답이 정확히 1개이고, 원문 빈칸 표현과 동일한가?
- [ ] 오답 4개는 원문 표현과 명확히 다른 의미인가?`}

**출력 시 주의:**
- "STEP 1", "검증" 등의 메타 텍스트는 출력하지 마세요
- 코드블록(\`\`\`) 없이 바로 "다음 글의 빈칸에..."로 시작
- 지문, 선택지, [정답], [해설]만 출력`;
};
